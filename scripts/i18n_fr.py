# A literal written in French in the code is stored in the catalogue under its
# ENGLISH value (see ENGLISH_OVERRIDES). On the next run the generator reads
# that English value back as the source, so the French has to be reachable from
# it too — otherwise every rerun quietly turned those labels English.
for _source, _english in ENGLISH_OVERRIDES.items():
    FRENCH.setdefault(_english, FRENCH.get(_source, _source))


# A multi-line label is written `\n` in the Kotlin source — two characters,
# not a line break. Python turns the same sequence into a real newline, which
# then matches nothing. Normalising here keeps the entries above readable.
FRENCH = {
    key.replace("\n", "\\n"): value.replace("\n", "\\n")
    for key, value in FRENCH.items()
}
ENGLISH_OVERRIDES = {
    key.replace("\n", "\\n"): value.replace("\n", "\\n")
    for key, value in ENGLISH_OVERRIDES.items()
}
